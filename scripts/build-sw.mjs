/**
 * Builds the worker app's service worker (slice 3.4): bundles src/sw/sw.ts with esbuild into
 * public/sw.js and injects the precache list. Runs before `next build` and `next dev`
 * (package.json), so the file is a plain static asset: nothing is bundled on request.
 *
 * Precached: the offline page (revision = the commit) and the worker app's icons and manifest
 * (revision = content hash). Hashed /_next/static files are cached as pages use them
 * (src/lib/offline/sw-routes.ts), not all up front, so workers never download the manager app.
 *
 * Why not @serwist/turbopack: its route handler needs `dynamic = "force-static"`, which Cache
 * Components rejects, so the service worker was not reliably prerendered and would be bundled
 * with esbuild on request in production.
 */
import { spawnSync } from "node:child_process";
import { createHash, randomUUID } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { buildSync } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(root, "public");

/** Must match WORKER_OFFLINE_PATH in src/lib/auth/routes.ts (checked by a unit test). */
export const OFFLINE_URL = "/m/offline";

function commit() {
  if (process.env.VERCEL_GIT_COMMIT_SHA) return process.env.VERCEL_GIT_COMMIT_SHA;
  const git = spawnSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf-8" });
  return git.stdout?.trim() || randomUUID();
}

const md5 = (file) => createHash("md5").update(readFileSync(file)).digest("hex");

export function precacheEntries() {
  const icons = readdirSync(path.join(publicDir, "icons"))
    .filter((name) => /^worker-[\w-]+\.png$/.test(name))
    .sort()
    .map((name) => ({ url: `/icons/${name}`, revision: md5(path.join(publicDir, "icons", name)) }));
  return [
    { url: OFFLINE_URL, revision: commit() },
    { url: "/worker.webmanifest", revision: md5(path.join(publicDir, "worker.webmanifest")) },
    ...icons,
  ];
}

function main() {
  const dev = process.argv.includes("--dev");
  const result = buildSync({
    entryPoints: [path.join(root, "src", "sw", "sw.ts")],
    outfile: path.join(publicDir, "sw.js"),
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    minify: !dev,
    sourcemap: false,
    legalComments: "none",
    define: {
      "self.__SW_MANIFEST": JSON.stringify(precacheEntries()),
      "process.env.NODE_ENV": JSON.stringify(dev ? "development" : "production"),
    },
    write: false,
    logLevel: "warning",
  });
  const out = result.outputFiles[0];
  if (!out) throw new Error("esbuild produced no service worker.");
  writeFileSync(out.path, `// Generated by scripts/build-sw.mjs. Do not edit.\n${out.text}`);
  console.log(`Service worker: public/sw.js (${Math.round(out.contents.length / 1024)} KiB)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
